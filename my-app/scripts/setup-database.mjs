import { randomBytes } from 'node:crypto';
import { appendFileSync } from 'node:fs';
import env from '@next/env';
import { localDatabaseConfig } from './database-config.mjs';

env.loadEnvConfig(process.cwd(), true);

try {
  if (process.env.DATABASE_URL) {
    localDatabaseConfig(process.env.DATABASE_URL);
    console.log('DATABASE_URL already configured. Existing credentials were preserved. Run bun run db:check.');
  } else {
    if (['MYSQL_USER', 'MYSQL_PASSWORD', 'MYSQL_ROOT_PASSWORD', 'MYSQL_DATABASE', 'MYSQL_PORT']
      .some(key => process.env[key])) {
      throw new Error('Partial MySQL configuration exists. Complete .env.local using .env.example; setup will not replace existing credentials.');
    }
    const password = randomBytes(24).toString('hex');
    const rootPassword = randomBytes(24).toString('hex');
    const configuration = [
      '', '# Local Zenvo database. Generated by db:setup; do not commit.',
      'MYSQL_DATABASE=zenvo', 'MYSQL_USER=zenvo', 'MYSQL_PORT=3307',
      `MYSQL_PASSWORD=${password}`, `MYSQL_ROOT_PASSWORD=${rootPassword}`,
      `DATABASE_URL=mysql://zenvo:${password}@127.0.0.1:3307/zenvo`, '',
    ].join('\n');
    appendFileSync('.env.local', configuration, { mode: 0o600 });
    console.log('Local database configuration saved to ignored .env.local. Run bun run db:up, then bun run db:check.');
  }
} catch (error) {
  // All configuration errors intentionally exclude credential values.
  console.error(error.message);
  process.exitCode = 1;
}
